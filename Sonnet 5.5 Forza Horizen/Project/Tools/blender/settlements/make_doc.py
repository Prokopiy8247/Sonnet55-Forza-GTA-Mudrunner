# -*- coding: utf-8 -*-
"""Writes Docs/Kits/settlements.md + Docs/Kits/settlements_kit.md from Exports/Settlements/*.json (plain python, no Blender needed).
Run:  python Tools/blender/settlements/make_doc.py"""
import os, json, glob

PROJECT = r"W:\YouTube\Claude Sonnet 5.5\Forza Horizen\Sonnet55Forza\UnrealSonnet55Forza"
EXP = os.path.join(PROJECT, 'Exports', 'Settlements')
DOCS = os.path.join(PROJECT, 'Docs', 'Kits')
os.makedirs(DOCS, exist_ok=True)

ORDER = ['bld_house_a', 'bld_house_b', 'bld_house_c', 'bld_house_l', 'bld_farmhouse', 'bld_barn', 'bld_silo', 'bld_church', 'bld_diner', 'bld_gas_station',
         'bld_chalet', 'bld_harbour_hut', 'bld_pier_4m', 'bld_boat_row', 'bld_boat_fishing_8m', 'bld_lighthouse', 'bld_windmill', 'bld_windmill_blades',
         'bld_wind_turbine', 'bld_wind_turbine_rotor', 'bld_castle_wall_6m', 'bld_castle_tower_ruin', 'bld_castle_arch']

rows = []
for aid in ORDER:
    p = os.path.join(EXP, aid + '.json')
    if os.path.exists(p):
        rows.append(json.load(open(p, encoding='utf8')))

def f(v):
    return '%.1f' % v

def bbox(d):
    return '%s x %s x %s' % (f(d['dimensions']['x']), f(d['dimensions']['y']), f(d['dimensions']['z']))

def foot(d):
    e = d.get('extra', {})
    if 'footprint' in e:
        return '%s x %s' % (f(e['footprint'][0]), f(e['footprint'][1]))
    if 'diameter' in e:
        return 'dia %s' % f(e['diameter'])
    if 'tower_radius' in e:
        return 'dia %s' % f(2 * e['tower_radius'])
    if 'radius' in e:
        return 'dia %s' % f(2 * e['radius'])
    if 'length' in e and 'width' in e:
        return '%s x %s' % (f(e['length']), f(e['width']))
    if 'length' in e and 'thickness' in e:
        return '%s x %s' % (f(e['length']), f(e['thickness']))
    if 'length' in e and 'beam' in e:
        return '%s x %s' % (f(e['length']), f(e['beam']))
    if 'opening_width' in e:
        return '7.6 x 1.2'
    return '%s x %s' % (f(d['dimensions']['x']), f(d['dimensions']['y']))

short = lambda mats: ', '.join(m.replace('M_Bld_', '') for m in mats)

# ----------------------------------------------------------------------------------------------------------------------
L = []
L.append('# Settlements kit - asset list (for the placement script)\n')
L.append('Generated by `Tools/blender/settlements/make_doc.py` from `Exports/Settlements/*.json`. Units: metres in Blender-space (UE = x100). '
         'Origin = ground centre of the footprint, +X = front/door side, +Z up (exceptions in the notes column).\n')
L.append('| id | name | footprint X x Y (m) | bbox X x Y x Z (m) | tris | materials | collision | scale | notes |')
L.append('|---|---|---|---|---|---|---|---|---|')
notes = {
    'bld_pier_4m': 'tileable: starts x=0, runs +X 4 m; z=0 = water, deck top 1.25',
    'bld_castle_wall_6m': 'tileable: starts x=0, runs +X 6 m, ends full height 4.7 m',
    'bld_windmill_blades': 'origin = hub; attach at windmill socket blades_hub (2.8,0,8.15); rotate about X',
    'bld_wind_turbine_rotor': 'origin = hub; attach at turbine socket rotor_hub (5.6,0,61.85); rotate about X',
    'bld_boat_row': 'keel at z=0; waterline z~0.16', 'bld_boat_fishing_8m': 'keel at z=0; waterline z~0.75',
    'bld_castle_tower_ruin': 'origin = tower centre; stubs run to -X / -Y',
}
tot = 0
for d in rows:
    t = d['tri_counts']['lod0']; tot += t
    L.append('| %s | %s | %s | %s | %d | %s | %s | %.2f-%.2f | %s |' % (d['id'], d['display_name'], foot(d), bbox(d), t, short(d['material_slots']),
             d['collision']['type'], d['scale_range'][0], d['scale_range'][1], notes.get(d['id'], '')))
L.append('\nTotal: %d assets, %d triangles (sum of LOD0).\n' % (len(rows), tot))
open(os.path.join(DOCS, 'settlements.md'), 'w', encoding='utf8').write('\n'.join(L))

# ----------------------------------------------------------------------------------------------------------------------
K = []
K.append('# Settlements kit (buildings + landmarks)\n')
K.append('Script source of truth: `Tools/blender/settlements/settlements_kit.py` (parts: `bld_lib.py`, `bld_houses.py`, `bld_farm.py`, `bld_civic.py`, `bld_coast.py`, '
         '`bld_landmarks.py`, `bld_ruins.py`). Idempotent: `_g = {"__name__":"bld_kit"}; exec(compile(open(path).read(), path, "exec"), _g); _g["build"]([...]); _g["validate_all"](); _g["export"](id)`.\n')
K.append('Blender staging: row `y = 100 m`, collections under `FORZA_UE/Settlements/<asset_id>`; exports `Exports/Settlements/<id>.fbx` + `<id>.json` (axis_forward -Y, axis_up Z, FBX_SCALE_ALL, one FBX per asset, `UCX_<id>_NN` hulls in the same FBX).\n')
K.append('## Conventions\n')
K.append('* 1 BU = 1 m, origin = ground centre of the footprint (bbox centre), +X = front/door side. All transforms applied, no negative scale.\n'
         '* UV: `UVMap` = metric box projection (1 UV unit = 1 m) for tiling UE materials; vertex colour `Col` = per-part tint (multiplied by the UE material, white default).\n'
         '* Materials (UE master-material instances by NAME): `M_Bld_Plaster, M_Bld_RoofTile, M_Bld_Wood, M_Bld_Stone, M_Bld_Metal, M_Bld_Window, M_Bld_Brick` + extras `M_Bld_PaintRed, M_Bld_PaintWhite, M_Bld_PaintBlue, M_Bld_Neon, M_Bld_Rubber` (<= 6 slots per asset).\n'
         '* `M_Bld_Window` = dark reflective glass with an emission colour parameter (strength 0 in Blender): drive it from the UE day/night cycle. `M_Bld_Neon` is emissive.\n'
         '* Tinted materials (Plaster, RoofTile, Wood, Stone, Brick, Paint*) multiply the `Col` vertex colour in Blender; mirror that in the UE master material (use `VertexColor` node).\n'
         '* Nanite: all opaque, no manual LODs. Use standard LODs only if the window material is set translucent.\n')
K.append('## Assets\n')
K.append('| id | bbox X x Y x Z (m) | footprint | tris | collision hulls (tris) | file |')
K.append('|---|---|---|---|---|---|')
for d in rows:
    K.append('| %s | %s | %s | %d | %d (%d tris) | `Exports/Settlements/%s.fbx` |' % (d['id'], bbox(d), foot(d), d['tri_counts']['lod0'], len(d['collision']['hulls']),
             sum(d['tri_counts']['collision'].values()) if d['tri_counts']['collision'] else 0, d['id']))
K.append('')
for d in rows:
    K.append('### %s - %s\n' % (d['id'], d['display_name']))
    K.append('* Usage: %s' % d['usage'])
    K.append('* Dimensions: bbox %s m, footprint %s m; tris %d; material slots: %s' % (bbox(d), foot(d), d['tri_counts']['lod0'], short(d['material_slots'])))
    K.append('* UE collision: `%s` (%d UCX hulls in the FBX); recommended scale range %.2f-%.2f; biome tags: %s' % (d['collision']['type'], len(d['collision']['hulls']),
             d['scale_range'][0], d['scale_range'][1], ', '.join(d['biome_tags'])))
    if d.get('sockets'):
        K.append('* Sockets (Blender metres, asset-local): %s' % json.dumps(d['sockets']))
    ex = {k: v for k, v in d.get('extra', {}).items() if k not in ('footprint',)}
    if ex:
        K.append('* Extra: %s' % json.dumps(ex))
    K.append('')
K.append('## UE usage notes\n')
K.append('* Buildings: place with the door facing the road (+X = front). Footprints in the table above are wall footprints; add the roof overhang (bbox) when checking clearance to roads/neighbours (keep >= 1 m).\n'
         '* Collision: import the FBX with its `UCX_*` hulls (Custom collision, no auto-generate). Rotor parts have no collision.\n'
         '* `bld_windmill_blades` / `bld_wind_turbine_rotor`: separate static meshes with pivot at the hub; attach to a Scene component at the documented socket and rotate about local X (RotatingMovement, ~20-40 deg/s for the turbine, ~15 deg/s for the windmill).\n'
         '* `bld_pier_4m`: chain along +X every 4.0 m (piles every 2 m keep the spacing uniform); z=0 is the water surface. `bld_castle_wall_6m` chains along +X every 6.0 m.\n'
         '* Boats: keel at z=0; set the actor so the waterline height (see Extra) sits on the water plane. No buoyancy/physics shipped.\n'
         '* Lighthouse: lantern glass (`M_Bld_Window`) is a separate material slot - add a spot light / rotating beam at `lantern_z` for night.\n'
         '* Randomise `Col`-tint-independent variety in UE via material instance parameters (plaster hue, roof hue) - geometry variants: 4 houses + farmhouse + chalet.\n')
K.append('## Known weaknesses\n')
K.append('\n'.join('* ' + w for w in [
    'Buildings are hollow shells without interiors (windows are opaque dark glass); no interior floors/rooms.',
    'Roof tiles are modelled as stepped courses (silhouette + shading) - the fine tile pattern must come from the UE material.',
    'Church windows/clock/belfry openings are applied relief (not real openings); houses/barn/diner/shop windows and doors are real openings with reveals.',
    'Ruin masonry uses 12-tri stone blocks with chamfered fronts: reads well at game distance, close-ups need a stone normal map.',
    'Wind-turbine blades are a stylised NACA-like airfoil loft (no internal structure); tower is a smooth tapered tube with flange rings.',
    'Boats are single static hulls (no interior detail below the thwarts, no rigging ropes); fishing boat hull is closed above the deck.',
    'No LOD chains were authored (Nanite assumed); `M_Bld_Window` translucency not used.',
    'Lighthouse/windmill/turbine bounding boxes are tall: check UE bounds scale / shadow distance settings.']))
open(os.path.join(DOCS, 'settlements_kit.md'), 'w', encoding='utf8').write('\n'.join(K))
print('wrote docs for', len(rows), 'assets, total tris', tot)
