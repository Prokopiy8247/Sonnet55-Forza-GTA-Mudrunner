# weapons_grenade_launcher.py - lane 5 - weapons/grenade_launcher (0.80 m, revolving drum). Needs gta_lib + weapons_common exec'd.
W = Wpn("grenade_launcher", 10)
RK = 0.30
def gb(z): return RK * z - 0.021
def gf(z): return RK * z + 0.019
BZ = 0.092
YM = 0.500

b = W.mb("Body")
# ---- frame: rear plate, front yoke, top/bottom straps ----
slab(b, [(-0.070, 0.042), (0.014, 0.034), (0.014, 0.146), (-0.058, 0.146), (-0.070, 0.132)], 0.0275, 0.0050, "MetalDark")
slab(b, [(0.112, 0.036), (0.152, 0.040), (0.152, 0.140), (0.112, 0.148)], 0.0275, 0.0050, "MetalDark")
slab(b, [(0.010, 0.1500), (0.114, 0.1500), (0.114, 0.1620), (0.010, 0.1620)], 0.0185, 0.0020, "MetalDark")
slab(b, [(0.010, 0.0200), (0.114, 0.0200), (0.114, 0.0330), (0.010, 0.0330)], 0.0185, 0.0020, "MetalDark")
# ---- barrel (40 mm) + sleeve + muzzle ----
rev(b, [(0.145, 0.0240), (YM, 0.0240)], 0, BZ, 8, "Gun", 22.5)
rev(b, [(0.185, 0.0285), (0.335, 0.0285)], 0, BZ, 8, "MetalDark", 22.5)
for y in (0.260,):
    rev(b, [(y - 0.003, 0.0300), (y + 0.003, 0.0300)], 0, BZ, 8, "Gun", 22.5)
rev(b, [(0.462, 0.0290), (YM, 0.0290)], 0, BZ, 8, "Gun", 22.5)
rev(b, [(YM - 0.0004, 0.0175), (YM + 0.0003, 0.0175)], 0, BZ, 8, "Trim", 22.5)
# ---- sights: front blade + ladder rear on the top strap ----
bx(b, (-0.0035, 0.0035), (0.440, 0.452), (BZ + 0.0270, BZ + 0.0480), "Gun")
bx(b, (-0.0011, 0.0011), (0.4385, 0.4402), (BZ + 0.0400, BZ + 0.0450), "SightDot")
bx(b, (-0.0150, 0.0150), (-0.052, -0.030), (0.146, 0.1620), "Gun")
bx(b, (-0.0150, 0.0150), (-0.052, -0.040), (0.1620, 0.1760), "Gun")
# ---- pistol grip + guard + mount ----
tbox(b, (-0.0220, 0.0220), (-0.050, 0.070), (0.030, 0.0460), "Gun", (-0.0200, 0.0200), (-0.044, 0.064))
grip = [(gb(0.050), 0.050), (gb(-0.085), -0.085), (gf(-0.085), -0.085), (gf(0.050), 0.050)]
slab(b, grip, 0.0185, 0.0030, "Grip")
grip_strips(b, gb, gf, RK, [-0.040], 0.0188)
guard = [(0.008, -0.026), (0.052, -0.026), (0.060, -0.018), (0.060, 0.034), (0.053, 0.034), (0.0525, -0.0125), (0.046, -0.0195), (0.008, -0.0195)]
slab(b, guard, 0.0115, 0.0016, "Grip")
# ---- vertical foregrip ----
tbox(b, (-0.0220, 0.0220), (0.196, 0.262), (0.050, 0.0680), "Gun", (-0.0200, 0.0200), (0.202, 0.256))
slab(b, [(0.208, 0.054), (0.202, -0.044), (0.242, -0.048), (0.254, 0.054)], 0.0180, 0.0035, "Grip")
# ---- skeletal wire stock ----
b.beam((0, -0.060, 0.128), (0, -0.292, 0.104), 0.0072, 0.0072, 6, "MetalDark")
b.beam((0, -0.060, 0.056), (0, -0.282, 0.046), 0.0072, 0.0072, 6, "MetalDark")
slab(b, [(-0.310, 0.034), (-0.290, 0.038), (-0.290, 0.110), (-0.310, 0.106)], 0.0200, 0.0030, "Trim")
W.part(b, "Body")

# ---- Cylinder (6 chambers) - pivot on its own axis ----
b = W.mb("Cylinder")
rev(b, [(0.012, 0.052), (0.018, 0.060), (0.106, 0.060), (0.112, 0.052)], 0, 0, 12, "GunLight", 0.0)
rev(b, [(0.050, 0.0615), (0.076, 0.0615)], 0, 0, 12, "GunAccent", 0.0)
for k in range(6):
    a = math.radians(60 * k)
    rev(b, [(0.1112, 0.0150), (0.1124, 0.0150)], 0.033 * math.cos(a), 0.033 * math.sin(a), 4, "Trim", 45.0)
W.part(b, "Cylinder", loc=(0, 0, BZ))

# ---- Trigger ----
b = W.mb("Trigger")
b.profile_extrude([(0.0290, 0.026), (0.0255, 0.008), (0.0295, -0.011), (0.0350, -0.0115), (0.0340, 0.008)], 0.0030, "MetalDark", 0.0)
W.part(b, "Trigger")

W.mark("Muzzle", (0, YM, BZ))
W.mark("Grip_L", (0, 0.226, -0.010))
W.mark("Eject", (0.0275, 0.060, BZ))
W.mark("AttOptic", (0, 0.060, 0.162))
W.mark("AttMuzzle", (0, YM, BZ))
W.mark("AttRail", (0, 0.160, BZ - 0.0285))
W.report()
